"""Read the local base-game database; emit auditable data and a limited Rust profile.

Does not assert patch precedence: db.zip is intentionally the explicit source.
Usage: python tools/import_ee2.py [installation]
"""
import csv
import hashlib
import io
import json
import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
INSTALL = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files (x86)\GOG.com\Empire Earth II')

def without_comments(text):
    return re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/',
                  lambda m: m[0] if m[0].startswith('"') else ' ', text, flags=re.S)

def block(text, kind, name):
    m = re.search(r'\b' + re.escape(kind) + r'\s+' + re.escape(name) + r'\s*\{', text)
    if not m:
        return ''
    depth = 1
    start = i = m.end()
    while i < len(text):
        if text[i] == '{': depth += 1
        if text[i] == '}': depth -= 1
        if depth == 0: return text[start:i]
        i += 1
    raise ValueError(f'Unclosed {kind} {name}')

def assignments(text):
    return {k: float(v) for k, v in re.findall(r'\b(\w+)\s*=\s*(-?\d+(?:\.\d+)?)\b', text)}

def run():
    archive = INSTALL / 'zips/db.zip'
    raw = archive.read_bytes()
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        names = {n.lower(): n for n in z.namelist()}
        def read(n): return z.read(names[n.lower()]).decode('utf-8-sig').replace('\r', '')
        path = 'db/TechTree/upgrade_unittypes.csv'
        lines = read(path).splitlines()
        header = next(csv.reader([lines[0].removeprefix('// ').strip()]))
        # Two DISPLAYNAME columns in the source are deliberately disambiguated.
        header[20] = 'DISPLAYNAME_PLURAL'
        rows = []
        for lineno, line in enumerate(lines[1:], 2):
            if not line.strip() or line.startswith('//'): continue
            vals = next(csv.reader([line]))
            if len(vals) != len(header): raise ValueError(f'{path}:{lineno}: {len(vals)} columns, expected {len(header)}')
            row = dict(zip(header, vals))
            for k in header[3:19]: row[k] = float(row[k]) if row[k] else 0
            row['source'] = f'db.zip!{path}:{lineno}'
            rows.append(row)
        combat = list(csv.reader(io.StringIO(read('db/Simulation/dbcombat.csv'))))
        combat = [r for r in combat if r]
        ch = next(r[1:] for r in combat if r[0].strip() == '//')
        matrix = {r[0]: dict(zip(ch, map(int, r[1:]))) for r in combat if not r[0].startswith('//')}
        if set(matrix) != set(ch) or any(len(r) != len(ch) for r in matrix.values()):
            raise ValueError('Combat matrix is not square')
        ddf = '\n'.join(without_comments(read(n)) for n in names if n.startswith('db/units/') and n.endswith('.ddf'))
        pairs = [('Destroyer','Destroyer',11),('Battleship','Battleship',11),
                 ('Submarine','Submarine',11),('Nuclear Submarine','Submarine',13),
                 ('Fighter','Fighter',11),('Bomber','Bomber',11),
                 ('Jet Fighter','Fighter',13),('Stealth Bomber','Bomber',15)]
        source = (ROOT/'src/defs.rs').read_text(encoding='utf-8')
        unit_names = re.findall(r'^\s+(?:unit|bld)\("([^"]+)"', source, re.M)
        generated = ['// Generated by tools/import_ee2.py; explicit BASE db.zip profile.',
                     '// Only listed unit stats change; economics, epochs and other rules remain OpenEpoch.',
                     'use crate::defs::*;',
                     f'pub const fn legacy(mut d: [Def; {len(unit_names)}]) -> [Def; {len(unit_names)}] {{']
        mappings = []
        turns = []
        for target, original, epoch in pairs:
            row = next(r for r in rows if r['UNIT'] == original and r['EPOCH'] == epoch)
            idx = unit_names.index(target)
            base = block(ddf,'UnitType',original)
            upgrade = block(ddf,'UpgradeAbilities',f'{original}Epoch{epoch}Attack')
            movement = {}
            for content in [base, upgrade]:
                for m in re.finditer(r'(?:NavalMove|AircraftMove)\s*\{([^}]+)\}', content): movement.update(assignments(m[1]))
            stats = {'hp': row['HP'], 'sight': row['LOS'], 'time': row['BUILDTIME']}
            if 'speed' in movement: stats['speed'] = movement['speed']
            if 'angSpeed' in movement: turns.append((idx, movement['angSpeed']))
            for k,v in stats.items(): generated.append(f'    d[{idx}].{k} = {float(v)};')
            for k,col in [('dmg','DAMAGE'),('range','RANGE'),('cd','RELOAD')]: generated.append(f'    d[{idx}].w[0].{k} = {float(row[col])};')
            # EE2 base nuclear submarine uses torpedoes; its missile attack is commented out.
            generated.append(f'    d[{idx}].w[1] = NOW;')
            if original in ('Destroyer', 'Battleship'):
                # Their EE2 combat-table columns include aircraft and submarines.
                generated.append(f'    d[{idx}].w[0].targets = LAND | SEA | AIR | SUB;')
            if original == 'Fighter': generated.append(f'    d[{idx}].w[0].targets = AIR;')
            if target == 'Stealth Bomber': generated.append(f'    d[{idx}].flags &= !F_STEALTH;')
            attack = assignments(' '.join(re.findall(r'Attack\s*\{([^}]+)\}',upgrade)))
            if 'areaDamageRadius' in attack: generated.append(f'    d[{idx}].w[0].splash = {attack["areaDamageRadius"]};')
            mappings.append({'openepoch':target, 'ee2':original,'epoch':epoch,'stats':stats,'movement':movement,'attack_ability':attack,'source':row['source']})
        generated += ['    let epochs = [0u8,2,5,9,10,11,13,14];', '    let mut i=0;', '    while i<d.len() {', '        d[i].epoch=epochs[d[i].epoch as usize];', '        if d[i].until<8 { d[i].until=epochs[d[i].until as usize]; }', '        i+=1;', '    }', '    d[0].epoch=0;', '    d[5].epoch=0;', '    d[49].epoch=0;', '    d[37].epoch=10;', '    d[38].epoch=10;', '    d[37].until=12;', '    d[38].until=14;', '    d[39].epoch=12;', '    d[40].epoch=14;', '    d[53].epoch=9;', '    d[54].epoch=12;', '    let mut c=18;', '    while c<=21 { d[c].made_at=STABLE; c+=1; }', '    d','}']
        generated += [f'pub const fn apply(d:[Def; {len(unit_names)}])->[Def; {len(unit_names)}] {{crate::economy::apply_original_defs(legacy(d))}}']
        generated += ['// Ghidra 007f10e0 multiplies angular speed by float at 00b42f0c.',
                      '// That float is 0.01745329238474369 (degrees -> radians).',
                      'pub fn turn_rate(id: u8) -> f32 {', '    match id {']
        generated += [f'        {idx} => {degrees} * 0.01745329238474369_f32,' for idx,degrees in turns]
        generated += ['        _ => 2.4,', '    }', '}']
        (ROOT/'src/ee2_profile.rs').write_text('\n'.join(generated)+'\n')
        result = {'source':str(archive),'sha256':hashlib.sha256(raw).hexdigest(),
                  'scope':'Base db.zip only. Patch overlay order, ability inheritance, missions, resources and full rules are not reconstructed.',
                  'rows':rows,'combat':matrix,'profile':mappings}
        (ROOT/'docs/ee2-reference.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
        print(f'Imported {len(rows)} upgrades; {len(matrix)}x{len(ch)} combat matrix; {len(mappings)} playable unit mappings')
        return result

if __name__ == '__main__': run()
