"""Generate UP initial definitions without importing any BASE legacy numeric layer."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def run():
    data=json.loads((ROOT/'docs/ee2-up15-units.json').read_text(encoding='utf8'))
    attack_json=ROOT/'docs/native-up15-attack.json'
    attack_rows=json.loads(attack_json.read_text())['rows'] if attack_json.exists() else []
    out=['// Generated by tools/import_ee2_up15_profile.py from resolved UP15 CSV5/CFG5.',
         '// Weapon kind/target mask, pathing and footprint are explicit smaller-engine adapters.',
         'use crate::defs::*;', 'pub const fn apply(mut d:[Def;57])->[Def;57]{',
         ' let epochs=[0u8,2,5,9,10,11,13,14];let mut i=0;',
         ' while i<d.len(){d[i].epoch=epochs[d[i].epoch as usize];if d[i].until<8{d[i].until=epochs[d[i].until as usize];}i+=1;}']
    for binding in data['bindings']:
        i=binding['id'];rows=[r for r in data['rows'] if r['id']==i]
        if not rows:
            out.append(f' d[{i}].epoch=255; // unresolved native binding: disabled in UP candidate')
            continue
        row=min(rows,key=lambda r:r['epoch']);fields=row['fields']
        for field,target in [('raw_speed','speed'),('damage','w[0].dmg'),('range','w[0].range'),('reload','w[0].cd')]:
            value=fields[field]['value']
            if value is not None:out.append(f' d[{i}].{target}={float(value)};')
        source_attack=next((r for r in attack_rows if r['id']==i and r['epoch']<=row['epoch']<r['until']),None)
        if source_attack:
            if source_attack['present'] and not source_attack['latent']:
                out.append(f' d[{i}].w[0].targets=LAND|SEA|AIR|SUB; // native RPS eligibility replaces prototype domains')
            elif not source_attack['present']:out.append(f' d[{i}].w[0].targets=0;')
        out.append(f' d[{i}].w[1]=NOW; // native source has a single Attack ability, not prototype secondary weapons')
    out+=[' crate::economy::apply_original_defs(d)','}',
          '// Unknown angular speeds retain explicit independent input adapter until bound.',
          'pub fn turn_rate_at(id:u8,epoch:u8)->f32{crate::ee2_up15_economy::lookup(id,epoch).and_then(|r|r.angular_speed).map(|v|v*0.01745329238474369_f32).unwrap_or(2.4)}',
          'pub fn turn_rate(id:u8)->f32{let epoch=crate::ee2_up15_economy::ROWS.iter().find(|r|r.id==id).map(|r|r.epoch).unwrap_or(0);turn_rate_at(id,epoch)}']
    extra=['// Generated from resolved UP15 inherited DDF fields; no BASE numeric layer.',
      '#[derive(Clone,Copy)] pub struct Extras {pub id:u8,pub epoch:u8,pub until:u8,pub angular_speed:Option<f32>,pub dropoff_bonus:Option<f32>}',
      'pub const ROWS:&[Extras]=&[']
    for row in data['class_rows']:
        opt=lambda key: 'None' if row['fields'][key]['value'] is None else 'Some('+str(float(row['fields'][key]['value']))+'_f32)'
        extra.append(f'Extras{{id:{row["id"]},epoch:{row["epoch"]},until:{row["until"]},angular_speed:{opt("angular_speed")},dropoff_bonus:{opt("dropoff_bonus")}}},')
    extra+= ['];',"pub fn lookup(id:u8,epoch:u8)->Option<&'static Extras>{ROWS.iter().find(|r|r.id==id&&epoch>=r.epoch&&epoch<r.until)}",
             'pub fn generation(id:u8,epoch:u8,resource:u8)->f32{crate::ee2_units::lookup_class(id,epoch).filter(|r|r.generation_resource==Some(resource)).and_then(|r|r.generation).unwrap_or(0.0)}']
    (ROOT/'src/ee2_up15_economy.rs').write_text('\n'.join(extra)+'\n')
    (ROOT/'src/ee2_up15_profile.rs').write_text('\n'.join(out)+'\n')
if __name__=='__main__':run()
