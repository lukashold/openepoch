"""Bind source-ordered global Main CSV upgrades to the existing61 definitions."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
def run():
    audit=json.loads((ROOT/'docs/roster6-availability.json').read_text(encoding='utf8'))
    units=json.loads((ROOT/'docs/ee2-roster6-units.json').read_text(encoding='utf8'))
    families={}
    for binding in units['bindings']:
        families.setdefault(binding['source_unit'],[]).append(binding['id'])
    rows=[]
    def walk(n,epoch,path):
        path=path+[n['name']]
        #0053C930 executes UpgradeRefs before applying its CSV scalars/reprice.
        for child in n.get('children',[]):walk(child,epoch,path)
        if n['kind']=='CSVUnitUpgrade':
            for ident in families.get(n['unit'],[]):
                rows.append({'epoch':epoch,'kind':'Reprice','def':ident,'upgrade':n['name'],'path':path,'source':n['source']})
        if n.get('obsoleteNode')=='FightingSail':
            rows.append({'epoch':epoch,'kind':'Obsolete','def':58,'upgrade':n['name'],'path':path,'source':n['source']})
    for main in audit['mainNodes']:
        if not main['TTCiv']:walk(main['graph'],main['epoch']-1,[])
    code=['// Source-ordered global Main actions; generated by generate_paid_queue7_main.py.',
          '#[derive(Clone,Copy)] pub enum Kind{Reprice,Obsolete}',
          'pub struct Action{pub epoch:u8,pub kind:Kind,pub def:crate::ids::DefId}',
          'pub const ACTIONS:&[Action]=&[']
    for row in rows:code.append(f'Action{{epoch:{row["epoch"]},kind:Kind::{row["kind"]},def:{row["def"]}}},')
    code.append('];')
    (ROOT/'src/paid_queue7_main.rs').write_text('\n'.join(code)+'\n',encoding='utf8')
    result={'format':'native-paidqueue7-main-order-v1','actions':rows,
            'sourceAvailabilitySha256':hashlib.sha256((ROOT/'docs/roster6-availability.json').read_bytes()).hexdigest(),
            'scope':'Only global Main CSV unit upgrades plus the proved additional FightingSail production obsolete action. Existing57 production gates and unimplemented Civ/Undo effects are not inferred.'}
    (ROOT/'docs/paidqueue7-main-actions.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf8')
    print(json.dumps({'actions':len(rows),'sail':[(r['epoch'],r['kind'])for r in rows if r['def']==58]}))
if __name__=='__main__':run()
